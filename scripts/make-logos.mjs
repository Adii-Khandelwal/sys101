// Offline pipeline: copy each company's mark from svgl (official brand SVGs) or, where svgl lacks it, Simple Icons (filled with the
// brand colour) into public/logos, and write lib/logoFiles.ts with each file's proportions. Idempotent; the site never fetches a logo
// at runtime. Run after editing content/logos.json: node scripts/make-logos.mjs
import fs from "node:fs";
import { chromium } from "playwright";

const cfg = JSON.parse(fs.readFileSync("content/logos.json", "utf8"));
const SVGL = "https://raw.githubusercontent.com/pheralb/svgl/main/static/library/";
const SI = `https://cdn.jsdelivr.net/npm/simple-icons@${cfg.simpleIcons.version}/`;
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const get = async (url) => {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${url}: HTTP ${r.status}`);
  return r;
};
const size = (svg) => {
  const v = svg.match(/viewBox="([\d.\s-]+)"/)?.[1].trim().split(/\s+/).map(Number);
  if (!v || v.length !== 4) throw new Error("no viewBox");
  return { w: v[2], h: v[3] };
};
const luminance = (hex) => {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};

fs.mkdirSync("public/logos", { recursive: true });
// Simple Icons draw every mark in a 24x24 square, so a wide wordmark floats in empty space. Crop the viewBox to the drawn shape
// (measured in a real browser) so the file carries the mark's true proportions.
const browser = await chromium.launch();
const page = await browser.newPage();
const bbox = async (d) => {
  await page.setContent(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><path id="p" d="${d}"/></svg>`);
  return page.evaluate(() => { const b = document.getElementById("p").getBBox(); return { x: b.x, y: b.y, w: b.width, h: b.height }; });
};
const siData = await (await get(SI + "data/simple-icons.json")).json();
const out = {};
for (const [name, src] of Object.entries(cfg.logos)) {
  const base = slug(name);
  const entry = {};
  if (src.svgl) {
    const files = [["", src.svgl], ["-dark", src.svglDark]].filter(([, f]) => f);
    for (const [suffix, f] of files) {
      const svg = await (await get(SVGL + f)).text();
      fs.writeFileSync(`public/logos/${base}${suffix}.svg`, svg);
      Object.assign(entry, suffix ? { dark: `/logos/${base}-dark.svg` } : { src: `/logos/${base}.svg`, ...size(svg) });
    }
    entry.source = "svgl";
  } else {
    const iconSlug = src.simpleIcons;
    const svg = await (await get(`${SI}icons/${iconSlug}.svg`)).text();
    const d = svg.match(/<path d="([^"]+)"/)?.[1];
    const hex = siData.find((i) => (i.slug ?? i.title.toLowerCase().replace(/[^a-z0-9]/g, "")) === iconSlug)?.hex;
    if (!d || !hex) throw new Error(`${iconSlug}: no path or brand colour`);
    if (luminance(`#${hex}`) < 0.08) throw new Error(`${iconSlug}: #${hex} is too dark for a dark page; add a dark variant`);
    const b = await bbox(d);
    const r = (n) => Math.round(n * 100) / 100;
    fs.writeFileSync(`public/logos/${base}.svg`, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${r(b.x)} ${r(b.y)} ${r(b.w)} ${r(b.h)}" fill="#${hex}"><path d="${d}"/></svg>\n`);
    Object.assign(entry, { src: `/logos/${base}.svg`, w: r(b.w), h: r(b.h), source: "simple-icons" });
  }
  out[name] = entry;
}
await browser.close();
const body = Object.entries(out).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
fs.writeFileSync(
  "lib/logoFiles.ts",
  `// Generated by scripts/make-logos.mjs from content/logos.json. Do not edit.\nexport type LogoFile = { src: string; dark?: string; w: number; h: number; source: "svgl" | "simple-icons" };\nexport const LOGO_FILES: Record<string, LogoFile> = {\n${body}\n};\n`,
);
console.log(`wrote ${Object.keys(out).length} logos`);
